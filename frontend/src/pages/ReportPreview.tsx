import { Download, Printer, ChevronLeft, AlertCircle } from 'lucide-react'
import { useState, useEffect } from 'react'
import { useParams, useNavigate } from 'react-router-dom'
import { cn } from '../lib/utils'
import { tm } from '../lib/ui'
import { api } from '../lib/api'

export function ReportPreview() {
  const { id }      = useParams()
  const navigate    = useNavigate()
  const [data,  setData]  = useState<any>(null)
  const [busy,  setBusy]  = useState(true)
  const [err,   setErr]   = useState('')

  useEffect(() => {
    if (!id) return
    const load = async () => {
      setBusy(true)
      try {
        const [tRes, sRes, mRes] = await Promise.all([
          api.get('/tenders/'),
          api.get(`/tenders/${id}/summary`).catch(() => ({ data: null })),
          api.post(`/tenders/${id}/match`).catch(() => ({ data: null })),
        ])
        const tender = tRes.data.find((t: any) => t.id === parseInt(id))
        setData({ tender, summary: sRes.data, match: mRes.data })
      } catch { setErr('Failed to load report data.') }
      finally { setBusy(false) }
    }
    load()
  }, [id])

  if (busy) return (
    <div className={cn(tm.card, 'flex flex-col items-center justify-center py-20 tm-in')}>
      <span className={cn(tm.spin, '!w-8 !h-8 mb-3')} />
      <p className="text-[13px] font-semibold text-text">Loading report…</p>
    </div>
  )

  if (err || !data?.tender) return (
    <div className="bg-bad-subtle border border-bad/20 text-bad p-6 rounded-xl flex flex-col items-center text-center">
      <AlertCircle size={28} className="mb-3" />
      <h2 className="text-[14px] font-bold mb-1">Report Generation Failed</h2>
      <p className="text-[13px]">
        {err || 'Tender not found. Make sure the tender exists and its summary has been generated.'}
      </p>
    </div>
  )

  const { tender, summary, match } = data
  const f = (name: string) => summary?.fields?.find((x: any) => x.field_name === name)?.extracted_value || '—'

  return (
    <div className="space-y-4 max-w-4xl mx-auto tm-up">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <button onClick={() => navigate(-1)} className={cn(tm.btn, tm.btnGhost, tm.btnIcon)}><ChevronLeft size={16} /></button>
          <div>
            <h1 className={tm.h1}>Analysis Report</h1>
            <p className={tm.sub}>AI-Generated Compliance and Summary Report</p>
          </div>
        </div>
        <div className="flex gap-2">
          <button onClick={() => window.print()}
            className={cn(tm.btn, tm.btnSec, tm.btnSm)}>
            <Printer size={13} /> Print
          </button>
          <button disabled className={cn(tm.btn, tm.btnGhost, tm.btnSm, 'opacity-40')}>
            <Download size={13} /> Export PDF
          </button>
        </div>
      </div>

      {/* Report body — uses bg-surface so it respects dark mode */}
      <div className={cn(tm.card, 'p-8 print:shadow-none print:border-none')}>
        {/* Report header */}
        <div className="text-center pb-6 mb-6 border-b border-border">
          <div className="w-10 h-10 bg-brand rounded-xl flex items-center justify-center mx-auto mb-3">
            <Download size={18} className="text-white" />
          </div>
          <h1 className="text-2xl font-bold text-text mb-1">Tender Analysis Report</h1>
          <h2 className="text-[15px] text-text2 mb-2">{tender.title}</h2>
          <p className="text-[12px] text-muted">Generated by TenderMind AI · {new Date().toLocaleDateString('en-GB', { day:'numeric', month:'long', year:'numeric' })}</p>
        </div>

        <div className="space-y-7">
          {/* 1. Executive Summary */}
          <section>
            <h3 className="text-[14px] font-bold text-brand border-b border-border pb-2 mb-3">
              1. Executive Summary
            </h3>
            {summary ? (
              <div className={cn(tm.cardHover, 'p-4 bg-subtle')}>
                <p className="text-[13px] text-text2 leading-relaxed whitespace-pre-wrap">
                  {f('Key Technical Requirements') !== '—'
                    ? f('Key Technical Requirements')
                    : 'Executive summary not available. Generate the tender summary first.'}
                </p>
              </div>
            ) : (
              <p className="text-[13px] text-muted italic">
                Executive summary not generated. Go to Tender Summary page first.
              </p>
            )}
          </section>

          {/* 2. Key Details */}
          {summary && (
            <section>
              <h3 className="text-[14px] font-bold text-brand border-b border-border pb-2 mb-3">
                2. Tender Key Details
              </h3>
              <div className={cn(tm.card, 'overflow-hidden')}>
                <table className="w-full text-sm">
                  <tbody className="divide-y divide-border">
                    {[
                      { l:'Tender Title',       k:'Tender Title'           },
                      { l:'Reference Number',   k:'Tender Reference Number'},
                      { l:'Organisation',       k:'Issuing Organization'   },
                      { l:'Estimated Value',    k:'Estimated Tender Value' },
                      { l:'EMD / Security',     k:'EMD / Bid Security'     },
                      { l:'Submission Deadline',k:'Bid Submission Deadline'},
                      { l:'Contract Duration',  k:'Contract Duration'      },
                    ].map(r => (
                      <tr key={r.k} className="hover:bg-subtle transition-colors">
                        <td className="px-4 py-2.5 text-[12px] font-semibold text-muted w-40">{r.l}</td>
                        <td className="px-4 py-2.5 text-[13px] text-text">{f(r.k)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </section>
          )}

          {/* 3. Eligibility & Compliance */}
          <section>
            <h3 className="text-[14px] font-bold text-brand border-b border-border pb-2 mb-3">
              3. Eligibility &amp; Compliance
            </h3>
            {!match ? (
              <p className="text-[13px] text-muted italic">
                Eligibility analysis not run. Go to Eligibility Match page first.
              </p>
            ) : (
              <>
                <div className="flex items-center gap-3 mb-4 p-3 bg-subtle rounded-lg">
                  <div className="w-10 h-10 rounded-lg flex items-center justify-center text-white font-bold text-lg"
                    style={{ background: match.score >= 70 ? 'hsl(var(--ok))' : match.score >= 40 ? 'hsl(var(--warn))' : 'hsl(var(--bad))' }}>
                    {match.score}%
                  </div>
                  <div>
                    <p className="text-[13px] font-bold text-text">Overall Match Score</p>
                    <p className="text-[12px] text-muted">
                      {match.matches?.filter((m: any) => m.status?.includes('Satisfied')).length || 0} satisfied ·{' '}
                      {match.matches?.filter((m: any) => m.status?.includes('Verification')).length || 0} needs review ·{' '}
                      {match.matches?.filter((m: any) => m.status?.includes('Unmet')).length || 0} unmet
                    </p>
                  </div>
                </div>

                <div className={cn(tm.card, 'overflow-hidden')}>
                  <table className="w-full text-sm">
                    <thead>
                      <tr className="bg-subtle border-b border-border">
                        <th className="px-4 py-2.5 text-[10px] font-bold text-muted uppercase tracking-widest text-left">Requirement</th>
                        <th className="px-4 py-2.5 text-[10px] font-bold text-muted uppercase tracking-widest text-left">Status</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-border">
                      {match.matches?.map((m: any, i: number) => (
                        <tr key={i} className="hover:bg-subtle transition-colors">
                          <td className="px-4 py-2.5 text-[12px] text-text">{m.description}</td>
                          <td className="px-4 py-2.5 text-[12px] font-semibold">
                            <span className={cn(
                              m.status?.includes('Satisfied') ? 'text-ok' :
                              m.status?.includes('Verification') ? 'text-warn' : 'text-bad'
                            )}>
                              {m.status}
                            </span>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </>
            )}
          </section>

          {/* 4. Technical Requirements */}
          {summary && f('Key Technical Requirements') !== '—' && (
            <section>
              <h3 className="text-[14px] font-bold text-brand border-b border-border pb-2 mb-3">
                4. Key Technical Requirements
              </h3>
              <p className="text-[13px] text-text2 leading-relaxed whitespace-pre-wrap">{f('Key Technical Requirements')}</p>
            </section>
          )}
        </div>

        {/* Footer */}
        <div className="mt-8 pt-4 border-t border-border text-center">
          <p className="text-[11px] text-muted">
            This report was generated by TenderMind AI. All information is sourced from uploaded documents.
            Verify all findings against original tender documents before making business decisions.
          </p>
        </div>
      </div>
    </div>
  )
}
